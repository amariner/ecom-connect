CREATE TRIGGER stage_supplier_product AFTER INSERT ON products
WHEN EXISTS (SELECT 1 FROM supplier_catalog_links WHERE code=NEW.supplier_sku AND linked=0)
BEGIN UPDATE products SET active=0 WHERE id=NEW.id; END;
CREATE TRIGGER stage_supplier_variant AFTER INSERT ON product_variants
WHEN EXISTS (SELECT 1 FROM products p JOIN supplier_catalog_links l ON l.code=p.supplier_sku WHERE p.id=NEW.product_id AND l.linked=0)
BEGIN UPDATE product_variants SET status='archived' WHERE id=NEW.id; END;
